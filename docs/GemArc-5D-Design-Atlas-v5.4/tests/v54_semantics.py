from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def check(name,value):
 checks.append({'name':name,'pass':bool(value)})
 if not value:raise AssertionError(name)
 print('PASS',name,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-gpu'])
 page=browser.new_page(viewport={'width':1440,'height':900})
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content((ROOT/'index.html').read_text(encoding='utf8'),wait_until='load')
 check('0D is internal (no 0D nav / view)',page.locator('#dimNav button').count()==5 and page.locator('button[data-dimension="0"]').count()==0 and page.locator('#view-0d').count()==0)
 page.locator('.nav[data-view="prompt"]').click()
 check('1D prompt screen usable',page.locator('.view.active').get_attribute('id')=='view-prompt')
 first=page.locator('#promptText').input_value()
 check('1D contains stable traced IDs', all(x in first for x in ('FR-APP-01','BD-APP-01','DD-APP-01','checkout')))
 page.locator('#promptFeature').select_option('FR-APP-05')
 check('1D scope regenerates', 'FR-APP-05' in page.locator('#promptText').input_value() and first!=page.locator('#promptText').input_value())
 page.locator('#promptStage').select_option('simulation')
 check('1D stage regenerates', '4D/5D 状态及因果设计' in page.locator('#promptText').input_value())
 check('1D export and copy controls',page.locator('#promptSave').is_enabled() and page.locator('#promptCopy').is_enabled())
 page.locator('button[data-dimension="2"]').click()
 check('2D node-edge independent diagram',page.locator('#graphLayer .g-node').count()==19 and page.locator('#graphLayer .g-edge').count()==26)
 page.locator('button[data-dimension="3"]').click()
 check('3D scene initialized',page.locator('#spatialScene canvas.gem-webgl').count()==1)
 page.locator('button[data-dimension="4"]').click()
 check('4D same graph and event scene',page.evaluate('(()=>{let c=document.querySelector("#timelineMount canvas.gem-webgl");return c?._gemPicks.nodes.length===19&&c._gemPicks.edges.length===26})()'))
 page.locator('button[data-dimension="5"]').click()
 check('5D same graph with independent edge picking',page.evaluate('(()=>{let c=document.querySelector("#causalMount canvas.gem-webgl");return c?._gemPicks.nodes.length===19&&c._gemPicks.edges.length===26})()'))
 check('5D normal/fail/recovery deterministic',page.evaluate('(()=>{let a=GemArcDesignAPI.runCase("CASE-CHECKOUT-001"),b=GemArcDesignAPI.runCase("CASE-CHECKOUT-001",{bOk:false}),c=GemArcDesignAPI.runCase("CASE-CHECKOUT-001",{bOk:false,recoverable:true});return [a.terminal,b.terminal,c.terminal].join(",")==="success,failed,recovered"})()'))
 check('144 case model terminals correct',page.evaluate('GEMARC_DESIGN_DATA.cases.every(c=>GemArcDesignAPI.runCase(c.id).terminal===c.expectedTerminal)'))
 check('41 embedded design docs include latest universal prompt',page.evaluate('GEMARC_DESIGN_DATA.docs.length===41 && GEMARC_DESIGN_DATA.docs.some(d=>d.id.includes("UNIVERSAL_5D_DESIGN"))'))
 check('no script exception',not errors)
 page.screenshot(path=str(ROOT/'previews/v54-5d-causal-final.png'),timeout=12000)
 browser.close()
(ROOT/'tests/acceptance-v54-results.json').write_text(json.dumps({'passed':len(checks),'total':len(checks),'checks':checks},ensure_ascii=False,indent=2),encoding='utf8')
print('SUMMARY',len(checks),'/',len(checks))
