import json, pathlib, threading, http.server, functools, socketserver
from playwright.sync_api import sync_playwright
root=pathlib.Path(__file__).resolve().parents[1]
errors=[];out={}
server=http.server.ThreadingHTTPServer(("127.0.0.1",0),functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(root)))
threading.Thread(target=server.serve_forever,daemon=True).start()
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--enable-unsafe-swiftshader'])
    page=browser.new_page(viewport={'width':1440,'height':900})
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.set_content((root/'index.html').read_text(encoding='utf8'),wait_until='load')
    page.wait_for_timeout(1300)
    out['title']=page.title()
    out['gpuStatus']=page.locator('#gpuStatus').inner_text()
    out['initialNode']=page.locator('#insTitle').inner_text()
    out['jsErrorsAfterLoad']=errors.copy()
    page.locator('[data-dim="1"]').click()
    out['promptBefore']=page.locator('#promptText').input_value()[:70]
    page.locator('#reqPick').select_option('REQ-003')
    out['promptChanges']='REQ-003' in page.locator('#promptText').input_value()
    page.locator('[data-dim="2"]').click()
    out['graphNodes']=page.locator('#graphSvg [data-id^="n."]').count()
    out['graphEdges']=page.locator('#graphSvg [data-id^="e"]').count()
    page.locator('#graphSvg [data-id="n.catalog"]').click(force=True)
    out['selected2D']=page.locator('#insTitle').inner_text()
    page.locator('[data-dim="3"]').click()
    page.wait_for_timeout(800)
    out['webglContext']=page.evaluate('Boolean(document.getElementById("space3d").getContext("webgl2")||document.getElementById("space3d").getContext("webgl"))')
    out['pixelsNotBlank']=page.evaluate('(()=>{const c=document.getElementById("space3d");const gl=c.getContext("webgl2")||c.getContext("webgl");if(!gl)return false;const p=new Uint8Array(4);gl.readPixels(Math.floor(c.width/2),Math.floor(c.height/2),1,1,gl.RGBA,gl.UNSIGNED_BYTE,p);return Array.from(p).some(x=>x>35)})()')
    page.locator('[data-dim="4"]').click()
    out['timelineEvents']=page.locator('#traceStrip .trace-chip').count()
    page.locator('#seek').fill('8')
    out['seekLabel']=page.locator('#clock').inner_text()
    page.locator('#casePick').select_option('CASE-PAY-TIMEOUT')
    out['caseSelection']=page.locator('#traceStrip .trace-chip').count()
    page.locator('[data-dim="5"]').click()
    out['baselineStatus']=page.locator('#resultBanner').inner_text()
    page.locator('#casePick').select_option('CASE-NORMAL')
    page.locator('#kindPick').select_option('Validator')
    page.locator('#disableEdge').select_option('e04')
    page.get_by_role('button',name='插入并重算').click()
    out['causalOutput']=page.locator('#resultBanner').inner_text()
    out['causalTraceCount']=page.locator('#traceStrip .trace-chip').count()
    out['causalDelta']=page.evaluate('Atlas && document.getElementById("causalSummary").innerText.includes("n.scenario.validator")')
    page.get_by_role('button',name='还原 A/B').click()
    out['resetCausal']=page.locator('#resultBanner').inner_text()
    page.locator('#diagramPick').select_option('ER Design')
    page.locator('#openDiagram').click()
    out['modalVisible']=page.locator('#diagramDialog').evaluate('(n)=>getComputedStyle(n).display!=="none"')
    out['allErrors']=errors
    (root/'tests/browser_screenshot.png').parent.mkdir(exist_ok=True,parents=True)
    page.locator('#diagramDialog').evaluate('(n)=>n.classList.remove("open")')
    page.screenshot(path=str(root/'tests/browser_screenshot.png'))
    browser.close()
server.shutdown()
(root/'tests/browser_results.json').write_text(json.dumps(out,ensure_ascii=False,indent=2))
print(json.dumps(out,ensure_ascii=False,indent=2))
